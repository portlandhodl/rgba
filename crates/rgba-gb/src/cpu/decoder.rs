/// struct SM83Operand
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct SM83Operand {
    pub reg: u8,
    pub flags: u8,
    pub immediate: u16,
}

/// struct SM83InstructionInfo
#[derive(Clone, Copy, Debug, Default)]
pub struct SM83InstructionInfo {
    pub opcode: [u8; 3],
    pub opcode_size: usize,
    pub op1: SM83Operand,
    pub op2: SM83Operand,
    pub mnemonic: u32,
    pub condition: u32,
}

// The C decoders are generated per-instruction by the DEFINE_*_SM83 macros and
// dispatched through `_sm83DecoderTable[0x100]` /
// `_sm83CBDecoderTable[0x100]` (built from DECLARE_SM83_EMITTER_BLOCK in
// emitter-sm83.h). Here the two tables are `match` statements in the exact
// order of those blocks; the helpers below play the role of the DEFINE_*
// macro bodies.

/// Maps an SM83 3-bit register encoding (order B, C, D, E, H, L, [HL], A, as
/// generated by DEFINE_*_DECODER_SM83's register lists) to an SM83_REG_* value
/// plus operand flags.
#[inline]
fn reg8(code: u8) -> (u8, u8) {
    match code {
        0 => (SM83_REG_B, 0),
        1 => (SM83_REG_C, 0),
        2 => (SM83_REG_D, 0),
        3 => (SM83_REG_E, 0),
        4 => (SM83_REG_H, 0),
        5 => (SM83_REG_L, 0),
        6 => (SM83_REG_HL, SM83_OP_FLAG_MEMORY),
        7 => (SM83_REG_A, 0),
        _ => unreachable!(),
    }
}

/// DEFINE_DECODER_SM83 default + DEFINE_RST_DECODER_SM83.
#[inline]
fn rst(info: &mut SM83InstructionInfo, vec: u16) -> usize {
    info.mnemonic = SM83_MN_RST;
    info.op1.immediate = vec;
    0
}

/// DEFINE_DECODER_SM83 with a bare mnemonic body (NOP, HALT, ...).
#[inline]
fn mnemonic(info: &mut SM83InstructionInfo, mn: u32) -> usize {
    info.mnemonic = mn;
    0
}

/// DEFINE_LD_DECODER_SM83's immediate form (LD r, d8).
#[inline]
fn ld_r_imm(info: &mut SM83InstructionInfo, reg: u8) -> usize {
    info.mnemonic = SM83_MN_LD;
    info.op1.reg = reg;
    1
}

/// DEFINE_LD_2_DECODER_SM83 (LD rr, d16).
#[inline]
fn ld_rr_imm(info: &mut SM83InstructionInfo, reg: u8) -> usize {
    info.mnemonic = SM83_MN_LD;
    info.op1.reg = reg;
    2
}

/// The 0x40..=0x7F block: DEFINE_LD_DECODER_SM83 for each register
/// (LD r, r' / LD r, [HL] / LD [HL], r). 0x76 (HALT) is excluded by the caller.
#[inline]
fn ld_r_r(opcode: u8, info: &mut SM83InstructionInfo) -> usize {
    let (dst, dst_flags) = reg8((opcode >> 3) & 7);
    let (src, src_flags) = reg8(opcode & 7);
    info.mnemonic = SM83_MN_LD;
    info.op1.reg = dst;
    info.op1.flags = dst_flags;
    info.op2.reg = src;
    info.op2.flags = src_flags;
    0
}

/// The 0x80..=0xBF block: DEFINE_ALU_DECODER_SM83_NOHL/MEM per group of 8
/// (ADD, ADC, SUB, SBC, AND, XOR, OR, CP over B, C, D, E, H, L, [HL], A).
#[inline]
fn alu_r(opcode: u8, info: &mut SM83InstructionInfo) -> usize {
    const ALU_MNEMONICS: [u32; 8] = [
        SM83_MN_ADD, SM83_MN_ADC, SM83_MN_SUB, SM83_MN_SBC, SM83_MN_AND, SM83_MN_XOR, SM83_MN_OR,
        SM83_MN_CP,
    ];
    let (reg, flags) = reg8(opcode & 7);
    info.mnemonic = ALU_MNEMONICS[((opcode >> 3) & 7) as usize];
    info.op1.reg = reg;
    info.op1.flags = flags;
    0
}

/// DEFINE_ALU_DECODER_SM83's immediate form (OP A, d8).
#[inline]
fn alu_imm(info: &mut SM83InstructionInfo, mn: u32) -> usize {
    info.mnemonic = mn;
    info.op1.reg = SM83_REG_A;
    info.op1.flags = SM83_OP_FLAG_IMPLICIT;
    1
}

/// DEFINE_JP_INSTRUCTION_SM83 / DEFINE_CALL_INSTRUCTION_SM83.
#[inline]
fn jp_call(info: &mut SM83InstructionInfo, mn: u32, condition: u32) -> usize {
    info.mnemonic = mn;
    info.condition = condition;
    2
}

/// DEFINE_JR_INSTRUCTION_SM83.
#[inline]
fn jr(info: &mut SM83InstructionInfo, condition: u32) -> usize {
    info.mnemonic = SM83_MN_JR;
    info.condition = condition;
    info.op1.flags = SM83_OP_FLAG_RELATIVE;
    1
}

/// _sm83DecoderTable[opcode], in DECLARE_SM83_EMITTER_BLOCK order.
fn decode_main(opcode: u8, info: &mut SM83InstructionInfo) -> usize {
    match opcode {
        0x00 => mnemonic(info, SM83_MN_NOP), // NOP
        0x01 => ld_rr_imm(info, SM83_REG_BC), // LDBC
        0x02 => {
            // LDBC_A
            info.mnemonic = SM83_MN_LD;
            info.op1.reg = SM83_REG_BC;
            info.op1.flags = SM83_OP_FLAG_MEMORY;
            info.op2.reg = SM83_REG_A;
            0
        }
        0x03 => {
            // INCBC (DEFINE_INCDEC_WIDE_INSTRUCTION_SM83)
            info.mnemonic = SM83_MN_INC;
            info.op1.reg = SM83_REG_BC;
            0
        }
        0x04 => {
            info.mnemonic = SM83_MN_INC;
            info.op1.reg = SM83_REG_B;
            0
        }
        0x05 => {
            info.mnemonic = SM83_MN_DEC;
            info.op1.reg = SM83_REG_B;
            0
        }
        0x06 => ld_r_imm(info, SM83_REG_B), // LDB_
        0x07 => {
            // RLCA_ (DEFINE_CB_X_DECODER_SM83's accumulator form)
            info.mnemonic = SM83_MN_RLC;
            info.op1.flags = SM83_OP_FLAG_IMPLICIT;
            info.op1.reg = SM83_REG_A;
            0
        }
        0x08 => {
            // LDISP (LD [a16], SP)
            info.mnemonic = SM83_MN_LD;
            info.op1.flags = SM83_OP_FLAG_MEMORY;
            info.op2.reg = SM83_REG_SP;
            2
        }
        0x09 => {
            // ADDHL_BC
            info.mnemonic = SM83_MN_ADD;
            info.op1.reg = SM83_REG_HL;
            info.op2.reg = SM83_REG_BC;
            0
        }
        0x0A => {
            // LDA_BC
            info.mnemonic = SM83_MN_LD;
            info.op1.reg = SM83_REG_A;
            info.op2.reg = SM83_REG_BC;
            info.op2.flags = SM83_OP_FLAG_MEMORY;
            0
        }
        0x0B => {
            info.mnemonic = SM83_MN_DEC;
            info.op1.reg = SM83_REG_BC;
            0
        }
        0x0C => {
            info.mnemonic = SM83_MN_INC;
            info.op1.reg = SM83_REG_C;
            0
        }
        0x0D => {
            info.mnemonic = SM83_MN_DEC;
            info.op1.reg = SM83_REG_C;
            0
        }
        0x0E => ld_r_imm(info, SM83_REG_C), // LDC_
        0x0F => {
            // RRCA_
            info.mnemonic = SM83_MN_RRC;
            info.op1.flags = SM83_OP_FLAG_IMPLICIT;
            info.op1.reg = SM83_REG_A;
            0
        }
        0x10 => mnemonic(info, SM83_MN_STOP), // STOP
        0x11 => ld_rr_imm(info, SM83_REG_DE), // LDDE
        0x12 => {
            // LDDE_A
            info.mnemonic = SM83_MN_LD;
            info.op1.reg = SM83_REG_DE;
            info.op1.flags = SM83_OP_FLAG_MEMORY;
            info.op2.reg = SM83_REG_A;
            0
        }
        0x13 => {
            info.mnemonic = SM83_MN_INC;
            info.op1.reg = SM83_REG_DE;
            0
        }
        0x14 => {
            info.mnemonic = SM83_MN_INC;
            info.op1.reg = SM83_REG_D;
            0
        }
        0x15 => {
            info.mnemonic = SM83_MN_DEC;
            info.op1.reg = SM83_REG_D;
            0
        }
        0x16 => ld_r_imm(info, SM83_REG_D), // LDD_
        0x17 => {
            // RLA_
            info.mnemonic = SM83_MN_RL;
            info.op1.flags = SM83_OP_FLAG_IMPLICIT;
            info.op1.reg = SM83_REG_A;
            0
        }
        0x18 => jr(info, SM83_COND_NONE), // JR
        0x19 => {
            // ADDHL_DE
            info.mnemonic = SM83_MN_ADD;
            info.op1.reg = SM83_REG_HL;
            info.op2.reg = SM83_REG_DE;
            0
        }
        0x1A => {
            // LDA_DE
            info.mnemonic = SM83_MN_LD;
            info.op1.reg = SM83_REG_A;
            info.op2.reg = SM83_REG_DE;
            info.op2.flags = SM83_OP_FLAG_MEMORY;
            0
        }
        0x1B => {
            info.mnemonic = SM83_MN_DEC;
            info.op1.reg = SM83_REG_DE;
            0
        }
        0x1C => {
            info.mnemonic = SM83_MN_INC;
            info.op1.reg = SM83_REG_E;
            0
        }
        0x1D => {
            info.mnemonic = SM83_MN_DEC;
            info.op1.reg = SM83_REG_E;
            0
        }
        0x1E => ld_r_imm(info, SM83_REG_E), // LDE_
        0x1F => {
            // RRA_
            info.mnemonic = SM83_MN_RR;
            info.op1.flags = SM83_OP_FLAG_IMPLICIT;
            info.op1.reg = SM83_REG_A;
            0
        }
        0x20 => jr(info, SM83_COND_NZ), // JRNZ
        0x21 => ld_rr_imm(info, SM83_REG_HL), // LDHL
        0x22 => {
            // LDIHLA (LD [HL+], A)
            info.mnemonic = SM83_MN_LD;
            info.op1.reg = SM83_REG_HL;
            info.op1.flags = SM83_OP_FLAG_INCREMENT | SM83_OP_FLAG_MEMORY;
            info.op2.reg = SM83_REG_A;
            0
        }
        0x23 => {
            info.mnemonic = SM83_MN_INC;
            info.op1.reg = SM83_REG_HL;
            0
        }
        0x24 => {
            info.mnemonic = SM83_MN_INC;
            info.op1.reg = SM83_REG_H;
            0
        }
        0x25 => {
            info.mnemonic = SM83_MN_DEC;
            info.op1.reg = SM83_REG_H;
            0
        }
        0x26 => ld_r_imm(info, SM83_REG_H), // LDH_
        0x27 => mnemonic(info, SM83_MN_DAA), // DAA
        0x28 => jr(info, SM83_COND_Z),      // JRZ
        0x29 => {
            // ADDHL_HL
            info.mnemonic = SM83_MN_ADD;
            info.op1.reg = SM83_REG_HL;
            info.op2.reg = SM83_REG_HL;
            0
        }
        0x2A => {
            // LDA_IHL (LD A, [HL+])
            info.mnemonic = SM83_MN_LD;
            info.op1.reg = SM83_REG_A;
            info.op2.reg = SM83_REG_HL;
            info.op2.flags = SM83_OP_FLAG_INCREMENT | SM83_OP_FLAG_MEMORY;
            0
        }
        0x2B => {
            info.mnemonic = SM83_MN_DEC;
            info.op1.reg = SM83_REG_HL;
            0
        }
        0x2C => {
            info.mnemonic = SM83_MN_INC;
            info.op1.reg = SM83_REG_L;
            0
        }
        0x2D => {
            info.mnemonic = SM83_MN_DEC;
            info.op1.reg = SM83_REG_L;
            0
        }
        0x2E => ld_r_imm(info, SM83_REG_L), // LDL_
        0x2F => mnemonic(info, SM83_MN_CPL), // CPL_
        0x30 => jr(info, SM83_COND_NC),     // JRNC
        0x31 => ld_rr_imm(info, SM83_REG_SP), // LDSP
        0x32 => {
            // LDDHLA (LD [HL-], A)
            info.mnemonic = SM83_MN_LD;
            info.op1.reg = SM83_REG_HL;
            info.op1.flags = SM83_OP_FLAG_DECREMENT | SM83_OP_FLAG_MEMORY;
            info.op2.reg = SM83_REG_A;
            0
        }
        0x33 => {
            info.mnemonic = SM83_MN_INC;
            info.op1.reg = SM83_REG_SP;
            0
        }
        0x34 => {
            // INC_HL (INC [HL])
            info.mnemonic = SM83_MN_INC;
            info.op1.reg = SM83_REG_HL;
            info.op1.flags = SM83_OP_FLAG_MEMORY;
            0
        }
        0x35 => {
            // DEC_HL (DEC [HL])
            info.mnemonic = SM83_MN_DEC;
            info.op1.reg = SM83_REG_HL;
            info.op1.flags = SM83_OP_FLAG_MEMORY;
            0
        }
        0x36 => {
            // LDHL_ (LD [HL], d8)
            info.mnemonic = SM83_MN_LD;
            info.op1.reg = SM83_REG_HL;
            info.op1.flags = SM83_OP_FLAG_MEMORY;
            1
        }
        0x37 => mnemonic(info, SM83_MN_SCF), // SCF
        0x38 => jr(info, SM83_COND_C),       // JRC
        0x39 => {
            // ADDHL_SP
            info.mnemonic = SM83_MN_ADD;
            info.op1.reg = SM83_REG_HL;
            info.op2.reg = SM83_REG_SP;
            0
        }
        0x3A => {
            // LDA_DHL (LD A, [HL-])
            info.mnemonic = SM83_MN_LD;
            info.op1.reg = SM83_REG_A;
            info.op2.reg = SM83_REG_HL;
            info.op2.flags = SM83_OP_FLAG_DECREMENT | SM83_OP_FLAG_MEMORY;
            0
        }
        0x3B => {
            info.mnemonic = SM83_MN_DEC;
            info.op1.reg = SM83_REG_SP;
            0
        }
        0x3C => {
            info.mnemonic = SM83_MN_INC;
            info.op1.reg = SM83_REG_A;
            0
        }
        0x3D => {
            info.mnemonic = SM83_MN_DEC;
            info.op1.reg = SM83_REG_A;
            0
        }
        0x3E => ld_r_imm(info, SM83_REG_A), // LDA_
        0x3F => mnemonic(info, SM83_MN_CCF), // CCF
        0x76 => mnemonic(info, SM83_MN_HALT), // HALT
        0x40..=0x7F => ld_r_r(opcode, info),
        0x80..=0xBF => alu_r(opcode, info),
        0xC0 => {
            // RETNZ (DEFINE_RET_INSTRUCTION_SM83)
            info.mnemonic = SM83_MN_RET;
            info.condition = SM83_COND_NZ;
            0
        }
        0xC1 => {
            // POPBC (DEFINE_POPPUSH_DECODER_SM83)
            info.mnemonic = SM83_MN_POP;
            info.op1.reg = SM83_REG_BC;
            0
        }
        0xC2 => jp_call(info, SM83_MN_JP, SM83_COND_NZ), // JPNZ
        0xC3 => jp_call(info, SM83_MN_JP, SM83_COND_NONE), // JP
        0xC4 => jp_call(info, SM83_MN_CALL, SM83_COND_NZ), // CALLNZ
        0xC5 => {
            // PUSHBC
            info.mnemonic = SM83_MN_PUSH;
            info.op1.reg = SM83_REG_BC;
            0
        }
        0xC6 => alu_imm(info, SM83_MN_ADD), // ADD
        0xC7 => rst(info, 0x00),            // RST00
        0xC8 => {
            info.mnemonic = SM83_MN_RET;
            info.condition = SM83_COND_Z;
            0
        }
        0xC9 => mnemonic(info, SM83_MN_RET), // RET
        0xCA => jp_call(info, SM83_MN_JP, SM83_COND_Z), // JPZ
        0xCB => 1,                           // CB prefix
        0xCC => jp_call(info, SM83_MN_CALL, SM83_COND_Z), // CALLZ
        0xCD => jp_call(info, SM83_MN_CALL, SM83_COND_NONE), // CALL
        0xCE => alu_imm(info, SM83_MN_ADC), // ADC
        0xCF => rst(info, 0x08),            // RST08
        0xD0 => {
            info.mnemonic = SM83_MN_RET;
            info.condition = SM83_COND_NC;
            0
        }
        0xD1 => {
            info.mnemonic = SM83_MN_POP;
            info.op1.reg = SM83_REG_DE;
            0
        }
        0xD2 => jp_call(info, SM83_MN_JP, SM83_COND_NC), // JPNC
        0xD3 => mnemonic(info, SM83_MN_ILL), // ILL
        0xD4 => jp_call(info, SM83_MN_CALL, SM83_COND_NC), // CALLNC
        0xD5 => {
            info.mnemonic = SM83_MN_PUSH;
            info.op1.reg = SM83_REG_DE;
            0
        }
        0xD6 => alu_imm(info, SM83_MN_SUB), // SUB
        0xD7 => rst(info, 0x10),            // RST10
        0xD8 => {
            info.mnemonic = SM83_MN_RET;
            info.condition = SM83_COND_C;
            0
        }
        0xD9 => mnemonic(info, SM83_MN_RETI), // RETI
        0xDA => jp_call(info, SM83_MN_JP, SM83_COND_C), // JPC
        0xDB => mnemonic(info, SM83_MN_ILL),
        0xDC => jp_call(info, SM83_MN_CALL, SM83_COND_C), // CALLC
        0xDD => mnemonic(info, SM83_MN_ILL),
        0xDE => alu_imm(info, SM83_MN_SBC), // SBC
        0xDF => rst(info, 0x18),            // RST18
        0xE0 => {
            // LDIOA (LDH [a8], A)
            info.mnemonic = SM83_MN_LDH;
            info.op1.immediate = 0xFF00;
            info.op1.flags = SM83_OP_FLAG_MEMORY;
            info.op2.reg = SM83_REG_A;
            1
        }
        0xE1 => {
            info.mnemonic = SM83_MN_POP;
            info.op1.reg = SM83_REG_HL;
            0
        }
        0xE2 => {
            // LDIOCA (LDH [C], A)
            info.mnemonic = SM83_MN_LDH;
            info.op1.reg = SM83_REG_C;
            info.op1.immediate = 0xFF00;
            info.op1.flags = SM83_OP_FLAG_MEMORY;
            info.op2.reg = SM83_REG_A;
            0
        }
        0xE3 => mnemonic(info, SM83_MN_ILL),
        0xE4 => mnemonic(info, SM83_MN_ILL),
        0xE5 => {
            info.mnemonic = SM83_MN_PUSH;
            info.op1.reg = SM83_REG_HL;
            0
        }
        0xE6 => alu_imm(info, SM83_MN_AND), // AND
        0xE7 => rst(info, 0x20),            // RST20
        0xE8 => {
            // ADDSP (ADD SP, r8)
            info.mnemonic = SM83_MN_ADD;
            info.op1.reg = SM83_REG_SP;
            1
        }
        0xE9 => {
            // JPHL
            info.mnemonic = SM83_MN_JP;
            info.op1.reg = SM83_REG_HL;
            0
        }
        0xEA => {
            // LDIA (LD [a16], A)
            info.mnemonic = SM83_MN_LD;
            info.op1.flags = SM83_OP_FLAG_MEMORY;
            info.op2.reg = SM83_REG_A;
            2
        }
        0xEB => mnemonic(info, SM83_MN_ILL),
        0xEC => mnemonic(info, SM83_MN_ILL),
        0xED => mnemonic(info, SM83_MN_ILL),
        0xEE => alu_imm(info, SM83_MN_XOR), // XOR
        0xEF => rst(info, 0x28),            // RST28
        0xF0 => {
            // LDAIO (LDH A, [a8])
            info.mnemonic = SM83_MN_LDH;
            info.op1.reg = SM83_REG_A;
            info.op2.immediate = 0xFF00;
            info.op2.flags = SM83_OP_FLAG_MEMORY;
            1
        }
        0xF1 => {
            info.mnemonic = SM83_MN_POP;
            info.op1.reg = SM83_REG_AF;
            0
        }
        0xF2 => {
            // LDAIOC (LDH A, [C])
            info.mnemonic = SM83_MN_LDH;
            info.op1.reg = SM83_REG_A;
            info.op2.reg = SM83_REG_C;
            info.op2.immediate = 0xFF00;
            info.op2.flags = SM83_OP_FLAG_MEMORY;
            0
        }
        0xF3 => mnemonic(info, SM83_MN_DI), // DI
        0xF4 => mnemonic(info, SM83_MN_ILL),
        0xF5 => {
            info.mnemonic = SM83_MN_PUSH;
            info.op1.reg = SM83_REG_AF;
            0
        }
        0xF6 => alu_imm(info, SM83_MN_OR), // OR
        0xF7 => rst(info, 0x30),           // RST30
        0xF8 => {
            // LDHL_SP (LD HL, SP+r8)
            info.mnemonic = SM83_MN_LD;
            info.op1.reg = SM83_REG_HL;
            info.op2.reg = SM83_REG_SP;
            1
        }
        0xF9 => {
            // LDSP_HL
            info.mnemonic = SM83_MN_LD;
            info.op1.reg = SM83_REG_SP;
            info.op2.reg = SM83_REG_HL;
            0
        }
        0xFA => {
            // LDAI (LD A, [a16])
            info.mnemonic = SM83_MN_LD;
            info.op1.reg = SM83_REG_A;
            info.op2.flags = SM83_OP_FLAG_MEMORY;
            2
        }
        0xFB => mnemonic(info, SM83_MN_EI), // EI
        0xFC => mnemonic(info, SM83_MN_ILL),
        0xFD => mnemonic(info, SM83_MN_ILL),
        0xFE => alu_imm(info, SM83_MN_CP), // CP
        0xFF => rst(info, 0x38),           // RST38
    }
}

/// _sm83CBDecoderTable[opcode], in DECLARE_SM83_CB_EMITTER_BLOCK order. The C
/// generates these from DEFINE_CB_*_DECODER_SM83 macros; the whole space is
/// regular: x = opcode >> 6, y = (opcode >> 3) & 7, z = opcode & 7.
fn decode_cb(opcode: u8, info: &mut SM83InstructionInfo) -> usize {
    let x = opcode >> 6;
    let y = (opcode >> 3) & 7;
    let z = opcode & 7;
    let (reg, flags) = reg8(z);
    match x {
        // DEFINE_CB_1_DECODER_SM83 / DEFINE_CB_X_DECODER_SM83: RLC, RRC, RL,
        // RR, SLA, SRA, SWAP, SRL — operand goes into op1.
        0 => {
            const CB_ROT_MNEMONICS: [u32; 8] = [
                SM83_MN_RLC, SM83_MN_RRC, SM83_MN_RL, SM83_MN_RR, SM83_MN_SLA, SM83_MN_SRA,
                SM83_MN_SWAP, SM83_MN_SRL,
            ];
            info.mnemonic = CB_ROT_MNEMONICS[y as usize];
            info.op1.reg = reg;
            info.op1.flags = flags;
        }
        // DEFINE_CB_DECODER_SM83: BIT/RES/SET y, r — bit index in
        // op1.immediate, operand in op2.
        1..=3 => {
            const CB_BIT_MNEMONICS: [u32; 3] = [SM83_MN_BIT, SM83_MN_RES, SM83_MN_SET];
            info.mnemonic = CB_BIT_MNEMONICS[(x - 1) as usize];
            info.op1.immediate = y as u16;
            info.op2.reg = reg;
            info.op2.flags = flags;
        }
        _ => unreachable!(),
    }
    0
}

/// SM83Decode: feed one byte of an instruction, returns how many additional
/// bytes must be fed (see the calling convention at the top of this file).
pub fn sm83_decode(opcode: u8, info: &mut SM83InstructionInfo) -> usize {
    if info.opcode_size == info.opcode.len() {
        return 0;
    }
    info.opcode[info.opcode_size] = opcode;
    match info.opcode_size {
        0 => {
            info.opcode_size += 1;
            decode_main(opcode, info)
        }
        1 if info.opcode[0] == 0xCB => {
            info.opcode_size += 1;
            decode_cb(opcode, info)
        }
        // Immediate operand bytes: accumulate little-endian into op2 if op1
        // names a register, otherwise into op1.
        _ => {
            info.opcode_size += 1;
            let shift = (info.opcode_size - 2) * 8;
            if info.op1.reg != 0 {
                info.op2.immediate |= (opcode as u16) << shift;
            } else {
                info.op1.immediate |= (opcode as u16) << shift;
            }
            0
        }
    }
}

