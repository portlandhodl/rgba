// Informational SM83 instruction decoder + disassembler, used by the debugger
// (it does NOT drive execution; the CPU executes via the microcoded handlers
// in `cpu/isa.rs`).
//
// Calling convention, mirroring mGBA's SM83DebuggerTrace
// (mgba/src/sm83/debugger/debugger.c): start from a zeroed
// `SM83InstructionInfo` and feed bytes one at a time; `sm83_decode` returns
// how many *additional* bytes must be fed to complete the instruction:
//
// ```text
// let mut info = SM83InstructionInfo::default();
// let mut bytes_remaining = 1;
// while bytes_remaining > 0 {
//     bytes_remaining += sm83_decode(next_byte(), &mut info);
//     bytes_remaining -= 1;
// }
// let text = sm83_disassemble(&info, address_after_instruction);
// ```
//
// The `pc` argument to `sm83_disassemble` is the address immediately after
// the (fully decoded) instruction, exactly as the C debugger passes it; JR
// targets are rendered relative to it.

