/// _sm83Conditions (index 0 is NULL in C).
const SM83_CONDITIONS: [Option<&'static str>; 5] =
    [None, Some("c"), Some("z"), Some("nc"), Some("nz")];

/// _sm83Registers
const SM83_REGISTERS: [&'static str; 15] = [
    "", "b", "c", "d", "e", "h", "l", "a", "f", "bc", "de", "hl", "af", "sp", "pc",
];

/// _sm83MnemonicStrings (note: SM83_MN_ILL renders as "--"; the trailing
/// "ill" at index SM83_MN_MAX is never selected by a decoder, same as C).
const SM83_MNEMONIC_STRINGS: [&'static str; (SM83_MN_MAX + 1) as usize] = [
    "--", "adc", "add", "and", "bit", "call", "ccf", "cp", "cpl", "daa", "dec", "di", "ei", "halt",
    "inc", "jp", "jr", "ld", "ldh", "nop", "or", "pop", "push", "res", "ret", "reti", "rl", "rlc",
    "rr", "rrc", "rst", "sbc", "scf", "set", "sla", "sra", "srl", "stop", "sub", "swap", "xor",
    "ill",
];

#[inline]
fn condition_str(condition: u32) -> Option<&'static str> {
    SM83_CONDITIONS.get(condition as usize).copied().flatten()
}

#[inline]
fn register_str(reg: u8) -> &'static str {
    SM83_REGISTERS.get(reg as usize).copied().unwrap_or("")
}

#[inline]
fn mnemonic_str(mnemonic: u32) -> &'static str {
    SM83_MNEMONIC_STRINGS
        .get(mnemonic as usize)
        .copied()
        .unwrap_or("--")
}

/// _decodeOperand: appends the operand's text to `out`; returns whether
/// anything was written (the C returns the character count, which
/// SM83Disassemble only tests for nonzero).
fn decode_operand(out: &mut String, op: &SM83Operand, pc: u16) -> bool {
    if op.flags & SM83_OP_FLAG_IMPLICIT != 0 {
        return false;
    }

    out.push(' ');

    if op.flags & SM83_OP_FLAG_MEMORY != 0 {
        out.push('[');
    }
    if op.reg != 0 {
        let _ = write!(out, "{}", register_str(op.reg));
    } else {
        if op.flags & SM83_OP_FLAG_RELATIVE != 0 {
            // C: snprintf(buffer, blen, "$%04X", pc + (int8_t) op.immediate);
            // evaluated in `int` and printed as unsigned.
            let target = (pc as i32).wrapping_add((op.immediate as u8 as i8) as i32);
            let _ = write!(out, "${:04X}", target as u32);
        } else {
            // C: "$%02X" — minimum width 2, widens for 16-bit immediates.
            let _ = write!(out, "${:02X}", op.immediate);
        }
        // The C has a dead `if (op.reg) "+"` here; op.reg is always 0 in this
        // branch, so it can never fire.
    }
    if op.flags & SM83_OP_FLAG_INCREMENT != 0 {
        out.push('+');
    }
    if op.flags & SM83_OP_FLAG_DECREMENT != 0 {
        out.push('-');
    }
    if op.flags & SM83_OP_FLAG_MEMORY != 0 {
        out.push(']');
    }
    true
}

/// SM83Disassemble: renders `info` as assembly text, byte-for-byte in the
/// C's format. `pc` is the address after the instruction. Unlike the C there
/// is no output buffer to truncate, so the full string is always returned.
pub fn sm83_disassemble(info: &SM83InstructionInfo, pc: u16) -> String {
    let mut out = String::new();
    let mnemonic = mnemonic_str(info.mnemonic);
    let _ = write!(out, "{}", mnemonic);
    // Mirrors the C's `written`, which is only ever tested for nonzero.
    let mut written = !mnemonic.is_empty();

    if let Some(cond) = condition_str(info.condition) {
        let _ = write!(out, " {}", cond);
        written = true;

        if info.op1.reg != 0 || info.op1.immediate != 0 || info.op2.reg != 0 || info.op2.immediate != 0
        {
            out.push(',');
            written = true;
        }
    }

    if info.op1.reg != 0 || info.op1.immediate != 0 || info.op2.reg != 0 || info.op2.immediate != 0 {
        written = decode_operand(&mut out, &info.op1, pc);
    }

    if info.op2.reg != 0
        || (info.op1.immediate == 0 && info.opcode_size > 1 && info.opcode[0] != 0xCB)
    {
        if written {
            out.push(',');
        }
        decode_operand(&mut out, &info.op2, pc);
    }

    out
}

