/// GBAMemoryInit's BIOS wiring (memory.c): install the HLE blob.
pub fn bios_install(gba: &mut Gba) {
    gba.memory.bios = HLE_BIOS.to_vec();
    gba.memory.full_bios = false;
}

/// GBAChecksum (bios.c)
pub fn gba_checksum(memory: &[u8]) -> u32 {
    let mut sum: u32 = 0;
    let n = memory.len() & !3;
    for i in (0..n).step_by(4) {
        sum = sum.wrapping_add(u32::from_le_bytes([memory[i], memory[i + 1], memory[i + 2], memory[i + 3]]));
    }
    sum
}

/// GBALoadBIOS (gba.c): install a real BIOS image if it passes sanity checks.
pub fn bios_load(gba: &mut Gba, bios: &[u8]) {
    if bios.len() != GBA_SIZE_BIOS {
        mlog!(Level::Warn, rgba_core::log::GBA, "Incorrect BIOS size");
        return;
    }
    let checksum = gba_checksum(bios);
    mlog!(Level::Debug, rgba_core::log::GBA, "BIOS Checksum: 0x{:X}", checksum);
    match checksum {
        GBA_BIOS_CHECKSUM => mlog!(Level::Info, rgba_core::log::GBA, "Official GBA BIOS detected"),
        GBA_DS_BIOS_CHECKSUM => mlog!(Level::Info, rgba_core::log::GBA, "Official GBA (DS) BIOS detected"),
        GBA_DEBUG_BIOS_CHECKSUM => {
            mlog!(Level::Warn, rgba_core::log::GBA, "Known broken GBA BIOS detected, disabling");
            return;
        }
        _ => mlog!(Level::Warn, rgba_core::log::GBA, "BIOS checksum incorrect"),
    }
    gba.memory.bios = bios.to_vec();
    gba.memory.full_bios = true;
    gba.bios_checksum = checksum;
    gba.has_bios = true;
}

/// GBAPrintFlush (memory.c). The AGB-print store path `_agbPrintStore` is a
/// stub in this crate (see cart/mod.rs), so only the drain+log and the
/// ctx.get writeback are meaningful here.
pub fn print_flush(gba: &mut Gba) {
    let Some(buf) = &gba.memory.agb_print_buffer else {
        return;
    };
    let mut out = String::with_capacity(0x100);
    let mut get = gba.memory.agb_print_ctx.get;
    let put = gba.memory.agb_print_ctx.put;
    let mut i = 0;
    while get != put && i < 0x100 {
        let mut value = i16::from_le_bytes([buf[(get & !1) as usize], buf[(get & !1) as usize + 1]]);
        if get & 1 != 0 {
            value >>= 8;
        } else {
            value &= 0xFF;
        }
        out.push((value as u8) as char);
        i += 1;
        get = get.wrapping_add(1);
    }
    // _agbPrintStore(gba, (AGB_PRINT_STRUCT + 4) | agbPrintBase, get):
    // the struct-range store just lands back in ctx.get.
    gba.memory.agb_print_ctx.get = get;
    mlog!(Level::Info, rgba_core::log::GBA_DEBUG, "{}", out);
}

fn mul_wait(r: i32) -> i32 {
    let r = r as u32;
    if (r & 0xFFFFFF00) == 0xFFFFFF00 || r & 0xFFFFFF00 == 0 {
        1
    } else if (r & 0xFFFF0000) == 0xFFFF0000 || r & 0xFFFF0000 == 0 {
        2
    } else if (r & 0xFF000000) == 0xFF000000 || r & 0xFF000000 == 0 {
        3
    } else {
        4
    }
}

